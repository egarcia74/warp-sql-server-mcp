#!/usr/bin/env node
/**
 * Fails when the documentation disagrees with `lib/tools/tool-registry.js` about which MCP
 * tools exist, or how many.
 *
 * This replaces the "Validate MCP tool documentation" step that lived in `docs.yml`, which
 * was worse than no check: it extracted tool names by running `/name:\s*['"]([^'"]+)['"]/g`
 * over `index.js`, and tool definitions moved to `lib/tools/tool-registry.js` some time ago.
 * The regex found exactly two matches, both of them the SERVER name, and `README.md` contains
 * that string everywhere - so the step reported "All tools are documented" unconditionally and
 * could not go red. Deleting every tool from the docs would not have failed it (#1265).
 *
 * ## What is checked, and why these three things
 *
 * The obvious check - "every tool name appears in README.md" - is the wrong one, and building
 * it would have turned CI red on all 16 tools at once. `README.md` documents none of them by
 * name, deliberately: it links to the generated reference at `docs/tools.html` and states a
 * COUNT. A hand-maintained list of tool signatures in the README would be the drift problem,
 * not the fix. So each surface is checked for the claim it actually makes:
 *
 * 1. `WARP.md` is the per-tool reference a contributor reads, and it does name every tool.
 *    A tool absent from it is undocumented in the only hand-written place that describes them.
 * 2. `README.md` asserts a number ("16 Database Tools", "Complete API reference (16 tools)").
 *    Nothing keeps those numerals honest when a tool is added or removed, and a stale count is
 *    the most visible possible inaccuracy - it is in the first screen of the project's front
 *    page. Every `tool-count` marker in either document must equal the registry count.
 * 3. `docs-data/tools.json` is generated by `npm run docs:build` and COMMITTED, so it is stale
 *    whenever someone changes the registry without regenerating. It carries its own
 *    `toolsCount` field, which can drift from its own `tools` array, so both are checked.
 *
 * Counts are read from an explicit `<!-- tool-count -->N<!-- /tool-count -->` marker rather
 * than from prose. Reading English for a number is a heuristic, and a heuristic in a required
 * gate fails in the expensive direction - see the note on TOOL_COUNT_MARKER below.
 *
 * The registry is IMPORTED rather than parsed. That is the whole lesson of the step this
 * replaces - a regex over a source file silently answers a different question the moment the
 * code moves.
 */

import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { getAllTools } from '../../lib/tools/tool-registry.js';
import { stripFencedBlocks, stripHtmlComments, stripRawTextHtml } from './markdown-blocks.mjs';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');

/** The hand-written reference that names every tool. */
export const TOOL_REFERENCE = 'WARP.md';

/** The front page, which claims a count rather than a list. */
export const COUNT_DOC = 'README.md';

/** Generated by `npm run docs:build` and committed, so it can be stale in a PR. */
export const GENERATED_DATA = 'docs-data/tools.json';

/**
 * The machine-readable count marker the documents carry, e.g.
 * `<!-- tool-count -->16<!-- /tool-count -->`, which renders as just the number.
 *
 * This replaces scanning prose for phrases like "16 database tools". That approach kept
 * producing findings in review, in both directions and for the same underlying reason: reading
 * English for a number is a heuristic, and heuristics in a REQUIRED gate fail in the expensive
 * direction. A pattern narrow enough to avoid false positives missed "16 different database
 * operation tools" in WARP.md; widening it to allow intervening words then read "We added 3 new
 * database tools" as a claim that the registry has three tools, which would fail CI on an
 * ordinary sentence.
 *
 * An explicit marker ends the argument. It is an exact string comparison with no normalisation,
 * so it cannot be fooled by phrasing, capitalisation, code spans or punctuation, and a writer
 * can put any words they like around it. The cost is three lines of Markdown; the benefit is a
 * claim that is machine-checkable rather than machine-guessed.
 */
export const TOOL_COUNT_MARKER = /<!--\s*tool-count\s*-->\s*(\d+)\s*<!--\s*\/tool-count\s*-->/g;

/**
 * Every count marker in a document, with the line it sits on.
 *
 * Read from the RAW Markdown deliberately: the marker is an HTML comment, so any normalisation
 * that strips comments would delete the thing being looked for.
 *
 * @param {string} markdown - Document contents
 * @returns {Array<{count: number, line: number}>} The markers found
 */
export function findCountMarkers(markdown) {
  return [...markdown.matchAll(TOOL_COUNT_MARKER)].map(match => ({
    count: Number(match[1]),
    line: markdown.slice(0, match.index).split('\n').length
  }));
}

const readRepoFile = relative => readFileSync(path.join(repoRoot, relative), 'utf8');

/**
 * Removes inline link destinations, keeping the link text.
 *
 * A scanner rather than `\\]\\([^)]*\\)`, because a Markdown destination may contain BALANCED
 * parentheses - `[guide](docs/foo(and)/new_tool.md)` is a valid link - and the pattern stopped
 * at the inner `)`, leaving `/new_tool.md)` behind. A tool named in that leftover then counted
 * as documented although no reader can see it. Nesting depth is tracked, and a backslash
 * escapes the character after it.
 */
export function stripLinkDestinations(text) {
  let out = '';
  let i = 0;

  while (i < text.length) {
    const open = text.indexOf('](', i);
    if (open === -1) return out + text.slice(i);

    out += text.slice(i, open + 1); // keep the link text and its closing bracket
    let depth = 1;
    let j = open + 2;

    while (j < text.length && depth > 0) {
      const ch = text[j];
      if (ch === '\\') j += 1;
      else if (ch === '(') depth += 1;
      else if (ch === ')') depth -= 1;
      j += 1;
    }

    // An unbalanced destination is not a link; keep it verbatim rather than eating the rest.
    if (depth !== 0) return out + text.slice(open + 1);
    i = j;
  }

  return out;
}

/**
 * A document reduced to what a reader actually SEES, for the purpose of finding tool names.
 *
 * Its two rules were each a bug once, in opposite directions:
 *
 * - An earlier version reused the count scanner's normalisation, which DELETES code spans.
 *   `WARP.md` documents tool names in backticks throughout, so a `### \`new_tool\`` heading -
 *   the most visible documentation a tool can have - was read as the tool being undocumented.
 *   A required check that fails a correct document is the one that gets switched off.
 * - Conversely, a name hidden in a link DESTINATION - `[tool guide](docs/new_tool.md)` - is
 *   not documentation; nobody reading the rendered page sees it. Tokenising the raw Markdown
 *   counted it, so a tool could be "documented" by a URL.
 *
 * So: drop the blocks a reader never sees, drop link destinations while keeping link text,
 * and unwrap code spans rather than deleting them.
 */
export function visibleText(markdown) {
  const withoutBlocks = stripHtmlComments(stripRawTextHtml(stripFencedBlocks(markdown)));

  return stripLinkDestinations(withoutBlocks)
    .replaceAll(/^\s*\[[^\]]+\]:\s*\S+.*$/gm, '') // reference-style link definitions
    .replaceAll('`', ' '); // unwrap code spans: the name inside is visible, the ticks are not
}

/**
 * Every whole word-token in a document, as a set.
 *
 * Tokenising once per document and testing membership avoids building a regular expression
 * per tool name, which Opengrep flags (`javascript_dos_rule-non-literal-regexp`) because a
 * dynamically constructed pattern is a denial-of-service surface wherever its input is not
 * trusted. Tool names come from the registry rather than from a user, so it was not
 * exploitable - but the check does not need a dynamic pattern at all, and a set lookup is
 * both simpler and O(document) instead of O(document x tools).
 */
export function wordTokens(text) {
  return new Set(text.split(/[^A-Za-z0-9_]+/));
}

/**
 * Whether a tool name appears in `text` as a whole token.
 *
 * `String.includes` is wrong here because tool names nest: `get_table` is a substring of
 * `get_table_data`, so a registry gaining `get_table` would look documented on the strength of
 * the older name alone. `\b` does not help either - `_` is a word character, so there is no
 * word boundary between `get_table` and `_data`. Splitting on runs of non-word characters puts
 * the whole identifier in one token, which is exactly the comparison wanted.
 */
export function mentionsTool(text, name) {
  return wordTokens(text).has(name);
}

/**
 * Compares the registry against the three documentation surfaces.
 *
 * Every input can be injected so the checks are testable against fixtures rather than against
 * the repository's own current state - a test that only asserts "the repo passes" cannot show
 * that the gate is able to fail.
 *
 * @param {object} [sources] - Overrides for the registry and the three documents
 * @returns {object} Counts, the failures in each direction, and `ok`
 */
export function checkToolDocs(sources = {}) {
  const tools = sources.tools ?? getAllTools().map(tool => tool.name);
  const reference = sources.reference ?? readRepoFile(TOOL_REFERENCE);
  const countDoc = sources.countDoc ?? readRepoFile(COUNT_DOC);
  const generated = sources.generated ?? JSON.parse(readRepoFile(GENERATED_DATA));

  const referenceTokens = wordTokens(visibleText(reference));
  const undocumented = tools.filter(name => !referenceTokens.has(name));

  // Both documents make count claims, so both are scanned. WARP.md:36 says "16 different
  // database operation tools" - a claim every bit as able to rot as the README's, and one that
  // would survive a tool being added, named in WARP.md and regenerated everywhere else.
  const countSources = [
    { doc: COUNT_DOC, text: countDoc },
    { doc: TOOL_REFERENCE, text: reference }
  ];
  const claims = countSources.flatMap(source =>
    findCountMarkers(source.text).map(marker => ({ ...marker, doc: source.doc }))
  );
  const staleClaims = claims.filter(claim => claim.count !== tools.length);

  // A document that carries no marker at all is drift too: deleting the marker would otherwise
  // be a silent way to stop the count being checked.
  const unmarked = countSources
    .filter(source => findCountMarkers(source.text).length === 0)
    .map(source => source.doc);

  const generatedTools = (generated?.tools ?? []).map(tool => tool.name);
  const missingFromData = tools.filter(name => !generatedTools.includes(name));
  const staleInData = [...new Set(generatedTools.filter(name => !tools.includes(name)))];

  // Set membership alone cannot see a repeated entry: every name is present, none is stale,
  // and `toolsCount` agrees with the array it was generated from - so the file renders a tool
  // twice and every check passes. Compare the counts and name the repeats.
  const duplicatesInData = [
    ...new Set(generatedTools.filter((name, index) => generatedTools.indexOf(name) !== index))
  ];
  // Anything that is not a number equal to the array length is wrong, including absent, null
  // and the string "16". A generated file that does not carry a valid count is not a file the
  // gate can vouch for, and treating a missing field as "nothing to check" is how a check ends
  // up reporting success over data it never looked at.
  const countFieldWrong = generated?.toolsCount !== generatedTools.length;

  return {
    tools,
    claims,
    undocumented,
    staleClaims,
    unmarked,
    missingFromData,
    staleInData,
    duplicatesInData,
    countFieldWrong,
    generatedCount: generatedTools.length,
    declaredCount: generated?.toolsCount ?? null,
    ok:
      undocumented.length === 0 &&
      staleClaims.length === 0 &&
      unmarked.length === 0 &&
      missingFromData.length === 0 &&
      staleInData.length === 0 &&
      duplicatesInData.length === 0 &&
      generatedTools.length === tools.length &&
      !countFieldWrong
  };
}

export function formatReport(result) {
  const list = names => names.map(name => `\`${name}\``).join(', ');
  const lines = [
    `**Tools declared by the registry**: ${result.tools.length}`,
    `**Tools named in \`${TOOL_REFERENCE}\`**: ${result.tools.length - result.undocumented.length}`,
    `**Tools in \`${GENERATED_DATA}\`**: ${result.generatedCount}`,
    `**Count markers checked**: ${result.claims.length}`
  ];

  if (result.undocumented.length > 0) {
    lines.push(`❌ **Not documented in \`${TOOL_REFERENCE}\`**: ${list(result.undocumented)}`);
  }
  for (const claim of result.staleClaims) {
    lines.push(
      `❌ **Stale count** in \`${claim.doc}\` line ${claim.line}: ` +
        `marker says ${claim.count}, the registry declares ${result.tools.length}`
    );
  }
  if (result.unmarked.length > 0) {
    lines.push(`❌ **No \`tool-count\` marker**: ${list(result.unmarked)}`);
  }
  if (result.missingFromData.length > 0) {
    lines.push(`❌ **Missing from \`${GENERATED_DATA}\`**: ${list(result.missingFromData)}`);
  }
  if (result.staleInData.length > 0) {
    lines.push(`❌ **Stale in \`${GENERATED_DATA}\`**: ${list(result.staleInData)}`);
  }
  if (result.duplicatesInData.length > 0) {
    lines.push(
      `❌ **Listed more than once in \`${GENERATED_DATA}\`**: ${list(result.duplicatesInData)}`
    );
  }
  if (result.countFieldWrong) {
    lines.push(
      `❌ **\`${GENERATED_DATA}\` disagrees with itself**: ` +
        `\`toolsCount\` is ${result.declaredCount}, but it lists ${result.generatedCount}`
    );
  }
  if (result.ok) {
    lines.push('✅ **Tool documentation matches the registry**');
  }

  return lines.join('\n');
}

function main() {
  const result = checkToolDocs();
  console.log(formatReport(result));

  if (result.ok) return;

  console.error('\n::error::Tool documentation has drifted from lib/tools/tool-registry.js.');
  if (result.undocumented.length > 0) {
    console.error(`  - document in ${TOOL_REFERENCE}: ${result.undocumented.join(', ')}`);
  }
  for (const claim of result.staleClaims) {
    console.error(`  - ${COUNT_DOC} line ${claim.line}: "${claim.text}" -> ${result.tools.length}`);
  }
  if (
    result.missingFromData.length > 0 ||
    result.staleInData.length > 0 ||
    result.countFieldWrong
  ) {
    console.error('  - regenerate the committed data: npm run docs:build');
  }
  process.exitCode = 1;
}

// Compare as file URLs: process.argv[1] is a plain filesystem path while import.meta.url is
// percent-encoded, so a hand-built `file://` + path string fails to match whenever the checkout
// contains a space, and main() would be skipped silently - exit 0, gate never run.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
