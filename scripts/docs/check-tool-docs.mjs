#!/usr/bin/env node
/**
 * Fails when `docs-data/tools.json` and `lib/tools/tool-registry.js` disagree about which MCP
 * tools exist.
 *
 * ## What this replaces
 *
 * `docs.yml` had a "Validate MCP tool documentation" step that could not fail. It extracted tool
 * names by running `/name:\s*['"]([^'"]+)['"]/g` over `index.js`, and the definitions had moved
 * to `lib/tools/tool-registry.js`: the regex matched twice, both times the SERVER name, which
 * `README.md` contains everywhere. It reported "All tools are documented" unconditionally, and
 * deleting every tool from the docs would not have failed it (#1265).
 *
 * ## Why this checks the generated data and not the prose
 *
 * The first version of this file also checked that `WARP.md` named every tool and that the
 * tool-count claims in `README.md` matched the registry. Both needed to interpret Markdown, and
 * across five review rounds every single finding against this file came from that interpretation
 * - in both directions, and each fix exposing the next case: code spans deleted a visible name,
 * then preserving them let a name in a link destination count; a count pattern narrow enough to
 * avoid false positives missed a real claim, and widening it read an ordinary sentence as one.
 * Moving the count to an explicit marker did not help either, because the marker still had to be
 * found in Markdown, and a marker inside a code fence counts as real.
 *
 * The comparison below has produced no such findings, because it interprets nothing: both sides
 * are structured data, and the check is set equality plus an integer. That is the difference
 * that matters - not how exact the rule is, but whether it has to understand a document to apply
 * it. Checking that the prose documents each tool is worth doing and is tracked separately; it
 * needs a real Markdown parser or a structured source, not another normalisation pass.
 *
 * `docs-data/tools.json` is generated by `npm run docs:build` and COMMITTED, so it goes stale
 * whenever the registry changes without a regeneration - and it is the input to
 * `generate-tools-html.js`, which produces the published reference.
 */

import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { getAllTools } from '../../lib/tools/tool-registry.js';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');

/** Generated by `npm run docs:build` and committed, so it can be stale in a pull request. */
export const GENERATED_DATA = 'docs-data/tools.json';

const readRepoFile = relative => readFileSync(path.join(repoRoot, relative), 'utf8');

/**
 * Compares the registry against the committed generated data.
 *
 * Both inputs can be injected so the checks are testable against fixtures rather than against
 * the repository's own current state - a suite that only asserts "the repo passes" cannot show
 * that the gate is able to fail, which is exactly how its predecessor went unnoticed.
 *
 * @param {object} [sources] - Overrides for the registry tool names and the generated data
 * @returns {object} Counts, the drift in each direction, and `ok`
 */
export function checkToolDocs(sources = {}) {
  const tools = sources.tools ?? getAllTools().map(tool => tool.name);
  const generated = sources.generated ?? JSON.parse(readRepoFile(GENERATED_DATA));

  const generatedTools = (generated?.tools ?? []).map(tool => tool.name);
  const missingFromData = tools.filter(name => !generatedTools.includes(name));
  const staleInData = [...new Set(generatedTools.filter(name => !tools.includes(name)))];

  // Set membership alone cannot see a repeated entry: every name is present, none is stale, and
  // `toolsCount` agrees with the array it was generated from - so the published reference renders
  // a tool twice and every check passes. Compare the lengths and name the repeats.
  const duplicatesInData = [
    ...new Set(generatedTools.filter((name, index) => generatedTools.indexOf(name) !== index))
  ];

  // Anything that is not a number equal to the array length is wrong, including absent, null and
  // the string "16". Treating a missing field as "nothing to check" is how a check ends up
  // reporting success over data it never looked at.
  const countFieldWrong = generated?.toolsCount !== generatedTools.length;

  return {
    tools,
    generatedCount: generatedTools.length,
    declaredCount: generated?.toolsCount ?? null,
    missingFromData,
    staleInData,
    duplicatesInData,
    countFieldWrong,
    ok:
      missingFromData.length === 0 &&
      staleInData.length === 0 &&
      duplicatesInData.length === 0 &&
      generatedTools.length === tools.length &&
      !countFieldWrong
  };
}

export function formatReport(result) {
  const list = names => names.map(name => `\`${name}\``).join(', ');
  const lines = [
    `**Tools declared by the registry**: ${result.tools.length}`,
    `**Tools in \`${GENERATED_DATA}\`**: ${result.generatedCount}`
  ];

  if (result.missingFromData.length > 0) {
    lines.push(`❌ **Missing from \`${GENERATED_DATA}\`**: ${list(result.missingFromData)}`);
  }
  if (result.staleInData.length > 0) {
    lines.push(`❌ **Stale in \`${GENERATED_DATA}\`**: ${list(result.staleInData)}`);
  }
  if (result.duplicatesInData.length > 0) {
    lines.push(
      `❌ **Listed more than once in \`${GENERATED_DATA}\`**: ${list(result.duplicatesInData)}`
    );
  }
  if (result.countFieldWrong) {
    lines.push(
      `❌ **\`${GENERATED_DATA}\` count field is wrong**: \`toolsCount\` is ` +
        `${JSON.stringify(result.declaredCount)}, but it lists ${result.generatedCount}`
    );
  }
  if (result.ok) {
    lines.push('✅ **Generated tool data matches the registry**');
  }

  return lines.join('\n');
}

function main() {
  const result = checkToolDocs();
  console.log(formatReport(result));

  if (result.ok) return;

  console.error(`\n::error::${GENERATED_DATA} has drifted from lib/tools/tool-registry.js.`);
  console.error('  - regenerate the committed data: npm run docs:build');
  process.exitCode = 1;
}

// Compare as file URLs: process.argv[1] is a plain filesystem path while import.meta.url is
// percent-encoded, so a hand-built `file://` + path string fails to match whenever the checkout
// contains a space, and main() would be skipped silently - exit 0, gate never run.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
