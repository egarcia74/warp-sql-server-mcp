#!/usr/bin/env node
/**
 * Fails when the documentation disagrees with `lib/tools/tool-registry.js` about which MCP
 * tools exist, or how many.
 *
 * This replaces the "Validate MCP tool documentation" step that lived in `docs.yml`, which
 * was worse than no check: it extracted tool names by running `/name:\s*['"]([^'"]+)['"]/g`
 * over `index.js`, and tool definitions moved to `lib/tools/tool-registry.js` some time ago.
 * The regex found exactly two matches, both of them the SERVER name, and `README.md` contains
 * that string everywhere - so the step reported "All tools are documented" unconditionally and
 * could not go red. Deleting every tool from the docs would not have failed it (#1265).
 *
 * ## What is checked, and why these three things
 *
 * The obvious check - "every tool name appears in README.md" - is the wrong one, and building
 * it would have turned CI red on all 16 tools at once. `README.md` documents none of them by
 * name, deliberately: it links to the generated reference at `docs/tools.html` and states a
 * COUNT. A hand-maintained list of tool signatures in the README would be the drift problem,
 * not the fix. So each surface is checked for the claim it actually makes:
 *
 * 1. `WARP.md` is the per-tool reference a contributor reads, and it does name every tool.
 *    A tool absent from it is undocumented in the only hand-written place that describes them.
 * 2. `README.md` asserts a number ("16 Database Tools", "Complete API reference (16 tools)").
 *    Nothing keeps those numerals honest when a tool is added or removed, and a stale count is
 *    the most visible possible inaccuracy - it is in the first screen of the project's front
 *    page. Every count claim found in prose must equal the registry count.
 * 3. `docs-data/tools.json` is generated by `npm run docs:build` and COMMITTED, so it is stale
 *    whenever someone changes the registry without regenerating. It carries its own
 *    `toolsCount` field, which can drift from its own `tools` array, so both are checked.
 *
 * Counts are read from prose only: fenced blocks, HTML comments and raw-text HTML are stripped
 * first (`markdown-blocks.mjs`), so an example in a code block cannot fail the gate.
 *
 * The registry is IMPORTED rather than parsed. That is the whole lesson of the step this
 * replaces - a regex over a source file silently answers a different question the moment the
 * code moves.
 */

import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { getAllTools } from '../../lib/tools/tool-registry.js';
import { stripFencedBlocks, stripHtmlComments, stripRawTextHtml } from './markdown-blocks.mjs';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');

/** The hand-written reference that names every tool. */
export const TOOL_REFERENCE = 'WARP.md';

/** The front page, which claims a count rather than a list. */
export const COUNT_DOC = 'README.md';

/** Generated by `npm run docs:build` and committed, so it can be stale in a PR. */
export const GENERATED_DATA = 'docs-data/tools.json';

/**
 * A prose claim about how many tools there are: "16 tools", "16 Database Tools",
 * "16 MCP tools". Deliberately narrow - it must be a number immediately followed by the word,
 * so "1,686 Tests" and a bare "16" elsewhere are not claims about the tool count.
 */
export const TOOL_COUNT_CLAIM = /(\d[\d,]*)\s+(?:Database\s+|MCP\s+)?[Tt]ools\b/g;

const readRepoFile = relative => readFileSync(path.join(repoRoot, relative), 'utf8');

/** Markdown with everything that is not prose removed, so examples cannot trip the gate. */
export function prose(markdown) {
  return stripRawTextHtml(stripHtmlComments(stripFencedBlocks(markdown)));
}

/**
 * Every tool-count claim in a document, with the line it sits on so a failure can be acted on
 * without hunting.
 * @param {string} markdown - Document contents
 * @returns {Array<{count: number, text: string, line: number}>} The claims found in prose
 */
export function findCountClaims(markdown) {
  const body = prose(markdown);
  const claims = [];

  for (const match of body.matchAll(TOOL_COUNT_CLAIM)) {
    claims.push({
      count: Number(match[1].replaceAll(',', '')),
      text: match[0],
      line: body.slice(0, match.index).split('\n').length
    });
  }

  return claims;
}

/**
 * Compares the registry against the three documentation surfaces.
 *
 * Every input can be injected so the checks are testable against fixtures rather than against
 * the repository's own current state - a test that only asserts "the repo passes" cannot show
 * that the gate is able to fail.
 *
 * @param {object} [sources] - Overrides for the registry and the three documents
 * @returns {object} Counts, the failures in each direction, and `ok`
 */
export function checkToolDocs(sources = {}) {
  const tools = sources.tools ?? getAllTools().map(tool => tool.name);
  const reference = sources.reference ?? readRepoFile(TOOL_REFERENCE);
  const countDoc = sources.countDoc ?? readRepoFile(COUNT_DOC);
  const generated = sources.generated ?? JSON.parse(readRepoFile(GENERATED_DATA));

  const referenceProse = prose(reference);
  const undocumented = tools.filter(name => !referenceProse.includes(name));

  const claims = findCountClaims(countDoc);
  const staleClaims = claims.filter(claim => claim.count !== tools.length);

  const generatedTools = (generated?.tools ?? []).map(tool => tool.name);
  const missingFromData = tools.filter(name => !generatedTools.includes(name));
  const staleInData = generatedTools.filter(name => !tools.includes(name));
  const countFieldWrong =
    typeof generated?.toolsCount === 'number' && generated.toolsCount !== generatedTools.length;

  return {
    tools,
    claims,
    undocumented,
    staleClaims,
    missingFromData,
    staleInData,
    countFieldWrong,
    generatedCount: generatedTools.length,
    declaredCount: generated?.toolsCount ?? null,
    ok:
      undocumented.length === 0 &&
      staleClaims.length === 0 &&
      missingFromData.length === 0 &&
      staleInData.length === 0 &&
      !countFieldWrong
  };
}

export function formatReport(result) {
  const list = names => names.map(name => `\`${name}\``).join(', ');
  const lines = [
    `**Tools declared by the registry**: ${result.tools.length}`,
    `**Tools named in \`${TOOL_REFERENCE}\`**: ${result.tools.length - result.undocumented.length}`,
    `**Tools in \`${GENERATED_DATA}\`**: ${result.generatedCount}`,
    `**Count claims in \`${COUNT_DOC}\`**: ${result.claims.length}`
  ];

  if (result.undocumented.length > 0) {
    lines.push(`❌ **Not documented in \`${TOOL_REFERENCE}\`**: ${list(result.undocumented)}`);
  }
  for (const claim of result.staleClaims) {
    lines.push(
      `❌ **Stale count** in \`${COUNT_DOC}\` line ${claim.line}: ` +
        `"${claim.text}" but the registry declares ${result.tools.length}`
    );
  }
  if (result.missingFromData.length > 0) {
    lines.push(`❌ **Missing from \`${GENERATED_DATA}\`**: ${list(result.missingFromData)}`);
  }
  if (result.staleInData.length > 0) {
    lines.push(`❌ **Stale in \`${GENERATED_DATA}\`**: ${list(result.staleInData)}`);
  }
  if (result.countFieldWrong) {
    lines.push(
      `❌ **\`${GENERATED_DATA}\` disagrees with itself**: ` +
        `\`toolsCount\` is ${result.declaredCount}, but it lists ${result.generatedCount}`
    );
  }
  if (result.ok) {
    lines.push('✅ **Tool documentation matches the registry**');
  }

  return lines.join('\n');
}

function main() {
  const result = checkToolDocs();
  console.log(formatReport(result));

  if (result.ok) return;

  console.error('\n::error::Tool documentation has drifted from lib/tools/tool-registry.js.');
  if (result.undocumented.length > 0) {
    console.error(`  - document in ${TOOL_REFERENCE}: ${result.undocumented.join(', ')}`);
  }
  for (const claim of result.staleClaims) {
    console.error(`  - ${COUNT_DOC} line ${claim.line}: "${claim.text}" -> ${result.tools.length}`);
  }
  if (
    result.missingFromData.length > 0 ||
    result.staleInData.length > 0 ||
    result.countFieldWrong
  ) {
    console.error('  - regenerate the committed data: npm run docs:build');
  }
  process.exitCode = 1;
}

// Compare as file URLs: process.argv[1] is a plain filesystem path while import.meta.url is
// percent-encoded, so a hand-built `file://` + path string fails to match whenever the checkout
// contains a space, and main() would be skipped silently - exit 0, gate never run.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
